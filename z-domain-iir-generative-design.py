def enforce_stability(a):
    poles = np.roots(a)
    stable = np.array([p if np.abs(p)<1 else 1/np.conj(p) for p in poles])
    new_a = np.poly(stable).astype(a.dtype)
    return new_a / new_a[0]

def freq_response(b, a, worN=512):
    w, h = signal.freqz(b, a, worN=worN)
    mag = 20*np.log10(np.abs(h)+1e-12)
    phase = np.unwrap(np.angle(h))
    return w, mag, phase

def impulse_response(b, a, n=50):
    delta = np.zeros(n); delta[0]=1.0
    return signal.lfilter(b, a, delta)

def to_ba(coeff):
    a = np.concatenate([[1.0], coeff[:ORDER]])
    b = coeff[ORDER:]
    return b, a

def unscale(coeff_scaled):
    return (coeff_scaled * std + mean).flatten()

