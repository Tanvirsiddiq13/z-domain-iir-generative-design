import os
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
from scipy import signal
from sklearn.decomposition import PCA
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader, TensorDataset
import copy, warnings
warnings.filterwarnings('ignore')

# ========================== CONFIGURATION ==========================
FILTER_DATA_PATH = "real_world_filters.csv"   # will be created with diverse filters

ORDER = 4                      # final filter order
N_COEFFS = 2 * ORDER + 1       # 9 coefficients per filter

LATENT_DIM = 8
HIDDEN_DIMS = [256, 128, 64]
BATCH_SIZE = 64
EPOCHS = 200
LEARNING_RATE = 1e-3
STABILITY_WEIGHT = 0.1
SEED = 42

np.random.seed(SEED)
torch.manual_seed(SEED)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f'Using device: {device}')

# ====================== 1. DIVERSE DATASET (FIXED ORDER) ======================
def generate_diverse_iir_dataset(n_samples=3000, order=ORDER):
    """
    Generate Butterworth, Chebyshev1/2, Elliptic filters of all types.
    For bandpass/bandstop we use order//2 so the final filter order remains 'order'.
    """
    np.random.seed(SEED)
    coeffs_list = []
    types_list = []

    for _ in range(n_samples):
        ftype = np.random.choice(['butter', 'cheby1', 'cheby2', 'ellip'])
        btype = np.random.choice(['lowpass', 'highpass', 'bandpass', 'bandstop'])

        # Adjust order for bandpass/bandstop to keep final order = ORDER
        if btype in ['lowpass', 'highpass']:
            N = order
        else:   # bandpass / bandstop -> effective order is 2*N
            N = order // 2   # order=4 -> N=2 gives final order 4

        try:
            # Build the filter
            if btype in ['lowpass', 'highpass']:
                Wn = np.random.uniform(0.1, 0.45)
                if btype == 'highpass':
                    Wn = np.clip(Wn, 0.1, 0.45)
            else:   # bandpass / bandstop
                Wn = np.sort(np.random.uniform(0.1, 0.45, 2))

            if ftype == 'butter':
                b, a = signal.butter(N, Wn, btype=btype, analog=False, output='ba')
            elif ftype == 'cheby1':
                rp = np.random.uniform(0.5, 3.0)
                b, a = signal.cheby1(N, rp, Wn, btype=btype, analog=False, output='ba')
            elif ftype == 'cheby2':
                rs = np.random.uniform(20, 60)
                b, a = signal.cheby2(N, rs, Wn, btype=btype, analog=False, output='ba')
            else:   # elliptic
                rp = np.random.uniform(0.5, 3.0)
                rs = np.random.uniform(20, 60)
                b, a = signal.ellip(N, rp, rs, Wn, btype=btype, analog=False, output='ba')

            # Ensure a0 = 1
            if a[0] != 1.0:
                b = b / a[0]
                a = a / a[0]

            # Keep only stable filters
            if np.all(np.abs(np.roots(a)) < 1.0):
                coeff = np.concatenate([a[1:], b])   # [a1..aN, b0..bN]
                coeffs_list.append(coeff)
                types_list.append(0 if btype in ['lowpass', 'bandpass'] else 1)
        except Exception:
            continue

    return np.array(coeffs_list, dtype=np.float32), np.array(types_list, dtype=np.int32)

# Create or load dataset
if not os.path.exists(FILTER_DATA_PATH):
    print("Creating diverse dataset (3000 filters, fixed order)...")
    all_coeffs, all_types = generate_diverse_iir_dataset(3000, ORDER)
    np.savetxt(FILTER_DATA_PATH, all_coeffs, delimiter=',', fmt='%.8f')
    print(f"Dataset saved to {FILTER_DATA_PATH}")
else:
    print(f"Loading dataset from {FILTER_DATA_PATH}")
    all_coeffs = np.loadtxt(FILTER_DATA_PATH, delimiter=',', dtype=np.float32)
    all_types = np.zeros(len(all_coeffs))   # no type info saved

print(f'Dataset shape: {all_coeffs.shape}')

# Split
np.random.seed(SEED)
indices = np.random.permutation(len(all_coeffs))
n_train = int(0.7 * len(all_coeffs))
n_val = int(0.15 * len(all_coeffs))
n_test = len(all_coeffs) - n_train - n_val

train_data = all_coeffs[indices[:n_train]]
val_data = all_coeffs[indices[n_train:n_train+n_val]]
test_data = all_coeffs[indices[n_train+n_val:]]
test_types = all_types[indices[n_train+n_val:]]

print(f'Train: {train_data.shape}, Val: {val_data.shape}, Test: {test_data.shape}')

# Normalise
mean = train_data.mean(axis=0, keepdims=True)
std = train_data.std(axis=0, keepdims=True) + 1e-8

train_scaled = (train_data - mean) / std
val_scaled = (val_data - mean) / std
test_scaled = (test_data - mean) / std

train_dataset = TensorDataset(torch.from_numpy(train_scaled))
val_dataset = TensorDataset(torch.from_numpy(val_scaled))
test_dataset = TensorDataset(torch.from_numpy(test_scaled))

train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True)
val_loader = DataLoader(val_dataset, batch_size=BATCH_SIZE, shuffle=False)
test_loader = DataLoader(test_dataset, batch_size=BATCH_SIZE, shuffle=False)

# ====================== 2. VAE MODEL (LayerNorm instead of BatchNorm) ======================
class ImprovedVAE(nn.Module):
    def __init__(self, input_dim, latent_dim=8, hidden_dims=[256,128,64]):
        super().__init__()
        # Encoder
        enc = []
        prev = input_dim
        for h in hidden_dims:
            enc.extend([nn.Linear(prev, h), nn.LayerNorm(h), nn.ReLU()])   # LayerNorm here
            prev = h
        self.encoder = nn.Sequential(*enc)
        self.mu = nn.Linear(prev, latent_dim)
        self.logvar = nn.Linear(prev, latent_dim)

        # Decoder
        dec = []
        prev = latent_dim
        for h in reversed(hidden_dims):
            dec.extend([nn.Linear(prev, h), nn.LayerNorm(h), nn.ReLU()])   # and here
            prev = h
        dec.append(nn.Linear(prev, input_dim))
        self.decoder = nn.Sequential(*dec)

    def encode(self, x):
        h = self.encoder(x)
        return self.mu(h), self.logvar(h)

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        return self.decoder(z), mu, logvar

# Stability penalty (same as before)
def pole_stability_loss(a_coeffs, order=ORDER):
    batch_size = a_coeffs.shape[0]
    loss = torch.tensor(0.0, device=a_coeffs.device)
    for i in range(batch_size):
        a_full = torch.cat([torch.ones(1, device=a_coeffs.device), a_coeffs[i, :order]])
        a_np = a_full.detach().cpu().numpy()
        poles = np.roots(a_np)
        for p in poles:
            if np.abs(p) > 1.0:
                loss = loss + (np.abs(p) - 1.0)**2
    return loss / batch_size

def vae_loss_stable(recon_x, x, mu, logvar, stab_weight=STABILITY_WEIGHT, beta=1.0):
    recon_loss = nn.functional.mse_loss(recon_x, x, reduction='mean')
    kl_loss = -0.5 * torch.mean(1 + logvar - mu.pow(2) - logvar.exp())
    stab_loss = pole_stability_loss(recon_x[:, :ORDER], ORDER)
    total = recon_loss + beta * kl_loss + stab_weight * stab_loss
    return total, recon_loss, kl_loss, stab_loss

# ====================== 3. TRAINING ======================
model = ImprovedVAE(N_COEFFS, latent_dim=LATENT_DIM, hidden_dims=HIDDEN_DIMS).to(device)
optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)
scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.5, patience=20)

history = {'train_loss':[], 'val_loss':[], 'recon':[], 'kl':[], 'stab':[]}
best_val_loss = float('inf')
best_state = None

print(f'\n--- Training VAE (latent {LATENT_DIM}D, {EPOCHS} epochs) ---')
for epoch in range(1, EPOCHS+1):
    model.train()
    train_loss_sum, r_sum, k_sum, s_sum = 0,0,0,0
    for batch in train_loader:
        x = batch[0].to(device)
        optimizer.zero_grad()
        recon, mu, logvar = model(x)
        loss, rec, kl, stab = vae_loss_stable(recon, x, mu, logvar)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        train_loss_sum += loss.item()
        r_sum += rec.item(); k_sum += kl.item(); s_sum += stab.item()

    history['train_loss'].append(train_loss_sum/len(train_loader))
    history['recon'].append(r_sum/len(train_loader))
    history['kl'].append(k_sum/len(train_loader))
    history['stab'].append(s_sum/len(train_loader))

    # Validation
    model.eval()
    val_loss_sum = 0
    with torch.no_grad():
        for batch in val_loader:
            x = batch[0].to(device)
            recon, mu, logvar = model(x)
            loss, _, _, _ = vae_loss_stable(recon, x, mu, logvar)
            val_loss_sum += loss.item()
    avg_val = val_loss_sum/len(val_loader)
    history['val_loss'].append(avg_val)
    scheduler.step(avg_val)

    if avg_val < best_val_loss:
        best_val_loss = avg_val
        best_state = copy.deepcopy(model.state_dict())

    if epoch % 20 == 0 or epoch == 1:
        print(f'Epoch {epoch:3d} | Train: {history["train_loss"][-1]:.4f} | Val: {avg_val:.4f} | '
              f'Recon: {history["recon"][-1]:.4f} | KL: {history["kl"][-1]:.4f} | '
              f'Stab: {history["stab"][-1]:.4f} | LR: {optimizer.param_groups[0]["lr"]:.6f}')

model.load_state_dict(best_state)
print('Training complete.\n')

